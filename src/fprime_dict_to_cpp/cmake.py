"""Emitting the ``CMakeLists.txt`` that builds a generated component.

Nothing is listed under ``DEPENDS``.  F Prime derives a module's dependencies from its
FPP model, so ``Fw.Com``, ``Fw.Log`` and -- for a queued component -- ``Svc.Sched`` are
picked up from the ``AUTOCODER_INPUTS`` without being named again here.  Naming them
twice is how a generated file goes stale the first time the model changes.
"""

from __future__ import annotations

from .cpp import cpp_file_names
from .plan import Plan

__all__ = ["render_cmake"]


def render_cmake(plan: Plan) -> str:
    """Render the ``CMakeLists.txt`` contents for ``plan``."""
    config = plan.config
    component = config.component

    autocoder_inputs = [f"{component}Types.fpp", f"{component}.fpp"]
    sources = [f"{component}.cpp", *(f"{name}.cpp" for name in cpp_file_names(plan))]
    headers = [f"{component}.hpp"]

    lines = [
        "####",
        f"# {component}: a proxy for the "
        f"{plan.dictionary.metadata.deployment_name} dictionary.",
        "#",
        "# Generated by fprime-dict-to-cpp.  Regenerate from the dictionary rather than",
        "# editing, and add this directory to the build with",
        "#",
        f'#     add_fprime_subdirectory("${{CMAKE_CURRENT_LIST_DIR}}/{component}")',
        "#",
        "# Module dependencies are derived from the FPP model, so they are not listed",
        "# again below.",
        "####",
        "",
        "register_fprime_module(",
        "  AUTOCODER_INPUTS",
        *(f'    "${{CMAKE_CURRENT_LIST_DIR}}/{name}"' for name in autocoder_inputs),
        "  SOURCES",
        *(f'    "${{CMAKE_CURRENT_LIST_DIR}}/{name}"' for name in sources),
        "  HEADERS",
        *(f'    "${{CMAKE_CURRENT_LIST_DIR}}/{name}"' for name in headers),
        ")",
    ]
    return "\n".join(lines) + "\n"
