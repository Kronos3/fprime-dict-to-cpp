def _port_types(writer: FppWriter, plan: Plan) -> None:
    """The port types the hooked ports take, declared beside the component.

    Beside rather than inside because FPP has no port definition among a component's
    members, which is also why these formals name the mirrored types through the
    component.

    One port type per hooked member rather than one shared type per kind: the formals *are*
    the member's, so a port that mirrors a command's arguments cannot be handed the wrong
    ones.
    """
    ports = plan.ports
    if not ports:
        return
    writer.comment(
        "One port type per hooked member, its formals taken from that member.  These are\n"
        "what lets flight software send a remote command, or hear about a remote event,\n"
        "without going through the ground interface."
    )
    for port in ports:
        writer.blank()
        _port_type(writer, port)
    writer.blank()


def _port_type(writer: FppWriter, port: PortPlan) -> None:
    params = []
    for param in port.params:
        text = f"{escape(param.name)}: {param.fpp}"
        if param.annotation:
            text = f"{text} @< {' '.join(param.annotation.split())}"
        params.append(text)
    writer.declaration(
        f"port {escape(port.type_name)}",
        params,
        (),
        annotation=f"{port.annotation}\n[{port.origin}]",
    )


def _ports(writer: FppWriter, plan: Plan) -> None:
    kind = plan.config.kind
    writer.banner("Ports")

    writer.annotate(
        "Packets received from the remote deployment.\n"
        + (
            "Queued, so decoding runs on this component's own thread rather than the "
            "caller's."
            if kind is ComponentKind.ACTIVE
            else (
                "Queued, and drained by the run port below."
                if kind is ComponentKind.QUEUED
                else "Decoded on the caller's thread."
            )
        )
    )
    writer.line(f"{kind.port_kind} comIn: Fw.Com")
    writer.blank()

    writer.annotate("Command packets addressed to the remote deployment.")
    writer.line("output port comOut: Fw.Com")

    if kind is ComponentKind.QUEUED:
        writer.blank()
        writer.annotate(
            "Drains the message queue.  A queued component has a queue but no thread "
            "of its own, so something has to call doDispatch; connect this to a rate "
            "group."
        )
        writer.line("sync input port run: Svc.Sched")

    _hooked_ports(writer, plan)

    writer.banner("Special ports")
    for annotation, declaration in (
        ("Command receive port", "command recv port cmdIn"),
        ("Command registration port", "command reg port cmdRegOut"),
        ("Command response port", "command resp port cmdResponseOut"),
        ("Event port", "event port logOut"),
        ("Text event port", "text event port logTextOut"),
        ("Telemetry port", "telemetry port tlmOut"),
        ("Time get port", "time get port timeCaller"),
    ):
        writer.annotate(annotation)
        writer.line(declaration)
        writer.blank()


def _hooked_ports(writer: FppWriter, plan: Plan) -> None:
    """The ports the configuration hooked onto individual members.

    An input port for a command is ``async`` wherever the component has a queue, for the
    same reason a forwarded command is: serializing a packet is quick, but a caller should
    not be made to wait on it, and a passive component has no queue to defer onto.
    """
    ports = plan.ports
    if not ports:
        return
    writer.banner("Hooked ports")
    writer.comment(
        "Ports onto individual members of the remote's interface, asked for by name in\n"
        "this component's configuration.  Their port types are declared above, beside\n"
        "this component."
    )
    writer.blank()
    for port in ports:
        writer.annotate(f"{port.annotation}\n[{port.origin}]")
        writer.line(f"{port.declaration} {escape(port.name)}: {escape(port.type_name)}")
        writer.blank()


