def _fragment_preamble(writer: FppWriter, plan: Plan, what: str) -> None:
    """The header every member fragment carries, naming what includes it."""
    metadata = plan.dictionary.metadata
    writer.comment(
        f"{plan.config.component}'s {what}, generated by fprime-dict-to-cpp.\n"
        f"\n"
        f"Included by {plan.config.component}.fpp, inside the component itself.\n"
        f"\n"
        f"Source deployment: {metadata.deployment_name}\n"
        f"\n"
        f"Do not edit: regenerate from the dictionary instead."
    )
    writer.blank()


def _params(plan: Plan, params: tuple[FormalParam, ...]) -> list[str]:
    """Render formal parameters, escaping any name FPP would read as a keyword."""
    rendered = []
    for param in params:
        text = f"{escape(param.name)}: {plan.spelling.fpp_type(param.type)}"
        if param.annotation:
            text = f"{text} @< {' '.join(param.annotation.split())}"
        rendered.append(text)
    return rendered


def render_commands(plan: Plan) -> str:
    """Render the ``<Component>Commands.fppi`` contents for ``plan``."""
    writer = FppWriter()
    _fragment_preamble(writer, plan, "commands")
    for command in plan.declared_commands:
        _command(writer, plan, command)
        writer.blank()
    return writer.render()


def _command(writer: FppWriter, plan: Plan, command: CommandPlan) -> None:
    kind = plan.config.kind.command_kind(command.source.kind)
    clauses = [f"opcode {command.local_opcode}"]
    writer.declaration(
        f"{kind} command {escape(command.identifier)}",
        _params(plan, command.source.params),
        clauses,
        annotation=_member_annotation(
            command.source.annotation,
            command.source.name,
            f"remote opcode {command.remote_opcode} (0x{command.remote_opcode:X}), "
            f"declared {command.source.kind.value} there",
        ),
    )


def render_events(plan: Plan) -> str:
    """Render the ``<Component>Events.fppi`` contents for ``plan``."""
    writer = FppWriter()
    _fragment_preamble(writer, plan, "events")
    for event in plan.declared_events:
        _event(writer, plan, event)
        writer.blank()
    _diagnostic_events(writer, plan)
    return writer.render()


def _event(writer: FppWriter, plan: Plan, event: EventPlan) -> None:
    clauses = [
        f"severity {event.source.severity.fpp}",
        f"id {event.local_id}",
        f"format {string_literal(event.source.format)}",
    ]
    if event.source.throttle is not None:
        clauses.append(f"throttle {event.source.throttle}")
    writer.declaration(
        f"event {escape(event.identifier)}",
        _params(plan, event.source.params),
        clauses,
        annotation=_member_annotation(
            event.source.annotation,
            event.source.name,
            f"remote id {event.remote_id} (0x{event.remote_id:X})",
        ),
    )


def render_telemetry(plan: Plan) -> str:
    """Render the ``<Component>Telemetry.fppi`` contents for ``plan``."""
    writer = FppWriter()
    _fragment_preamble(writer, plan, "telemetry channels")
    for channel in plan.declared_channels:
        _channel(writer, plan, channel)
        writer.blank()
    _diagnostic_channels(writer, plan)
    return writer.render()


def _channel(writer: FppWriter, plan: Plan, channel: ChannelPlan) -> None:
    source = channel.source
    clauses = [f"id {channel.local_id}", source.update.fpp]
    if source.format:
        clauses.append(f"format {string_literal(source.format)}")
    for side, limit in (("low", source.limits.low), ("high", source.limits.high)):
        if limit:
            clauses.append(f"{side} {{ {_limit_entries(limit)} }}")
    writer.declaration(
        f"telemetry {escape(channel.identifier)}: {plan.spelling.fpp_type(source.type)}",
        (),
        clauses,
        annotation=_member_annotation(
            source.annotation,
            source.name,
            f"remote id {channel.remote_id} (0x{channel.remote_id:X})",
        ),
    )


#: What the proxy's own health telemetry and events say about the link.
#:
#: Fixed rather than derived: these describe the *link*, which no dictionary knows
#: anything about.  The argument types are deliberately widened to ``U32`` so the
#: declarations do not change with the remote's descriptor or id widths.
_DIAGNOSTIC_PREAMBLE = (
    "This component's own health, not mirrored from the remote dictionary.\n"
    "Without it, a link dropping or garbling packets looks the same as a quiet one."
)


def _diagnostic_channels(writer: FppWriter, plan: Plan) -> None:
    channel_ids = plan.diagnostic_channel_ids
    if not channel_ids:
        return

    writer.banner("Proxy diagnostics")
    writer.comment(_DIAGNOSTIC_PREAMBLE)
    writer.blank()

    for name, annotation in (
        ("ProxyPacketsDecoded", "Packets decoded into events or telemetry"),
        ("ProxyDecodeErrors", "Packets that could not be decoded"),
        (
            "ProxyPacketsIgnored",
            "Packets whose descriptor or identifier this proxy does not mirror",
        ),
        (
            "ProxyForwardErrors",
            "Command packets a hooked input port could not send",
        ),
    ):
        if name not in channel_ids:
            continue
        writer.declaration(
            f"telemetry {name}: U32",
            (),
            [f"id {channel_ids[name]}", "update on change"],
            annotation=annotation,
        )
        writer.blank()


def _diagnostic_events(writer: FppWriter, plan: Plan) -> None:
    event_ids = plan.diagnostic_event_ids
    if not event_ids:
        return

    writer.banner("Proxy diagnostics")
    writer.comment(_DIAGNOSTIC_PREAMBLE)
    writer.blank()

    if "ProxyDecodeError" in event_ids:
        writer.declaration(
            "event ProxyDecodeError",
            [
                "descriptor: U32 @< The packet descriptor",
                "identifier: U32 @< The event, channel or packet id, if it was read",
                "status: I32 @< The Fw::SerializeStatus that stopped the decode",
            ],
            [
                "severity warning high",
                f"id {event_ids['ProxyDecodeError']}",
                'format "Could not decode packet: descriptor {}, id {}, status {}"',
                "throttle 10",
            ],
            annotation="A packet from the remote deployment did not deserialize",
        )
        writer.blank()

    if "ProxyPacketIgnored" in event_ids:
        writer.declaration(
            "event ProxyPacketIgnored",
            [
                "descriptor: U32 @< The packet descriptor",
                "identifier: U32 @< The event, channel or packet id, if it was read",
            ],
            [
                "severity diagnostic",
                f"id {event_ids['ProxyPacketIgnored']}",
                'format "Ignored packet: descriptor {}, id {}"',
                "throttle 10",
            ],
            annotation=(
                "A well-formed packet named something this proxy does not mirror.\n"
                "Expected for packet kinds outside this proxy's scope, such as files\n"
                "and data products."
            ),
        )
        writer.blank()

    if "ProxyForwardError" in event_ids:
        writer.declaration(
            "event ProxyForwardError",
            [
                # Not "opcode": FPP reserves that word, and an escaped $opcode would
                # reach the generated C++ as a formal called opcode anyway.
                "remoteOpcode: U32 @< The remote opcode that was being forwarded",
                "status: I32 @< The Fw::SerializeStatus, or OK if comOut is unconnected",
            ],
            [
                "severity warning high",
                f"id {event_ids['ProxyForwardError']}",
                'format "Could not forward remote opcode {} to the remote deployment: '
                'status {}"',
                "throttle 10",
            ],
            annotation=(
                "A hooked input port could not send its command packet.\n"
                "A forwarded ground command reports this as a command response instead;\n"
                "a port has no caller to answer, which is why this exists."
            ),
        )
        writer.blank()


def _limit_entries(limit: Limit) -> str:
    """The inside of a ``low``/``high`` limit set, in FPP's declaration order."""
    entries = [
        f"{name} {_number(value)}"
        for name, value in (
            ("red", limit.red),
            ("orange", limit.orange),
            ("yellow", limit.yellow),
        )
        if value is not None
    ]
    return ", ".join(entries)


def _number(value: object) -> str:
    """An FPP numeric literal.  Floats keep a decimal point so the type stays float."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        text = repr(value)
        return text if ("." in text or "e" in text or "E" in text) else f"{text}.0"
    return str(value)


def _member_annotation(annotation: str | None, origin: object, note: str) -> str:
    """A member's annotation, plus a provenance line naming the remote entry."""
    lines = list(annotation.splitlines()) if annotation else []
    lines.append(f"[{origin}] {note}")
    return "\n".join(lines)
