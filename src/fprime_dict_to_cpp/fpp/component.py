"""Emitting the proxy component's FPP model.

The declarations here are what gives the target deployment's ground dictionary an entry
for every one of the remote's commands, events and channels -- which is the whole point
of generating a component rather than tunnelling opaque packets.

Ids and opcodes are **local and dense**.  F Prime offsets them by the base id the target
topology assigns this instance; the remote's absolute values live only in the generated
C++, which matches them against the wire.
"""

from __future__ import annotations

from ..model import ComponentKind, FormalParam, Limit
from ..plan import ChannelPlan, CommandPlan, EventPlan, Plan
from .keywords import escape
from .writer import FppWriter, string_literal

__all__ = ["render_component"]


def render_component(plan: Plan) -> str:
    """Render the ``<Component>.fpp`` contents for ``plan``."""
    writer = FppWriter()
    _preamble(writer, plan)
    config = plan.config
    with writer.module(config.namespace):
        writer.annotate(_component_annotation(plan))
        with writer.block(
            f"{config.kind.value} component {escape(config.component)} {{"
        ):
            _ports(writer, plan)
            _commands(writer, plan)
            _events(writer, plan)
            _telemetry(writer, plan)
            _diagnostics(writer, plan)
    return writer.render()


def _preamble(writer: FppWriter, plan: Plan) -> None:
    metadata = plan.dictionary.metadata
    writer.comment(
        f"{plan.config.component}, generated by fprime-dict-to-cpp.\n"
        f"\n"
        f"Source deployment: {metadata.deployment_name}\n"
        f"Framework version: {metadata.framework_version}\n"
        f"Project version:   {metadata.project_version}\n"
        f"\n"
        f"Do not edit: regenerate from the dictionary instead."
    )
    writer.blank()


def _component_annotation(plan: Plan) -> str:
    counts = (
        f"{len(plan.declared_commands)} commands, {len(plan.declared_events)} events, "
        f"{len(plan.declared_channels)} telemetry channels"
    )
    lines = [
        f"Proxies the {plan.dictionary.metadata.deployment_name} dictionary "
        f"({counts}).",
        "",
        (
            "Decodes Fw.Com packets received from the remote deployment into this "
            "component's own events and telemetry, and serializes each of its commands "
            "into an outgoing Fw.Com command packet."
            if plan.declared_commands or plan.declared_events or plan.declared_channels
            # Every member is omitted, so nothing of the remote's interface is declared
            # here and the ports below are the whole of what this component does.
            else "Declares none of the remote's interface itself: every command, event "
            "and telemetry channel is omitted, so the hooked ports below are what this "
            "component is for."
        ),
    ]
    if plan.has_packets:
        lines.append(
            f"Also unpacks {len(plan.packets)} packetized-telemetry packet layouts."
        )
    if plan.ports:
        lines.append(
            f"{len(plan.input_ports)} of the remote's commands and "
            f"{len(plan.output_ports)} of its reports are also hooked onto ports of "
            f"this component, for flight software rather than for the ground."
        )
    return "\n".join(lines)


