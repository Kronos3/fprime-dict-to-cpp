"""Emitting ``kind: types``: FPP structs for each command and telemetry packet.

Three files, each declaring into the configured namespace:

* ``<Name>Types.fpp`` -- every type the structs reach, flattened
  (``Ref_DpDemo_ColorEnum``), and the remote's top-level ones as ``Remote_<name>``.
* ``<Name>Commands.fpp`` -- a ``Command`` module with one struct per command, holding its
  arguments, and an ``Opcode`` module with a constant per command of the same name.
* ``<Name>Packets.fpp`` -- a ``Packet`` module with one struct per telemetry packet,
  holding its channels, and a ``PacketId`` module with a constant per packet.

The commands and packets files name the types file's definitions, so they go into a
build together.
"""

from __future__ import annotations

from collections.abc import Sequence

from ..spelling import safe_identifier
from ..structs import (
    COMMAND_MODULE,
    OPCODE_MODULE,
    PACKET_ID_MODULE,
    PACKET_MODULE,
    StructField,
    StructsPlan,
    type_name,
)
from .keywords import escape
from .typedefs import render_definition
from .writer import FppWriter

__all__ = ["STRUCT_FILES", "render_structs", "struct_file_names"]

#: Every file a ``types`` run may write, by the section name that suffixes it.
STRUCT_FILES = ("Types", "Commands", "Packets")


def render_structs(plan: StructsPlan) -> dict[str, str]:
    """Every file for ``plan``, keyed by file name.

    A section with nothing in it is not written: an empty file is one more thing to keep
    in the build for no reason.
    """
    name = plan.config.component
    files: dict[str, str] = {}
    if plan.type_defs:
        files[f"{name}Types.fpp"] = _render_types(plan)
    if plan.commands:
        files[f"{name}Commands.fpp"] = _render_commands(plan)
    if plan.packets:
        files[f"{name}Packets.fpp"] = _render_packets(plan)
    return files


def struct_file_names(plan: StructsPlan) -> list[str]:
    """The file names :func:`render_structs` would produce, in the same order."""
    return list(render_structs(plan))


def _preamble(
    writer: FppWriter, plan: StructsPlan, what: str, needs_types: bool
) -> None:
    metadata = plan.dictionary.metadata
    writer.comment(
        f"Generated by fprime-dict-to-cpp: {what}.\n"
        f"\n"
        f"Source deployment: {metadata.deployment_name}\n"
        f"Framework version: {metadata.framework_version}\n"
        f"Dictionary spec:   {metadata.spec_version}\n"
        f"\n"
        f"Do not edit: regenerate from the dictionary instead."
    )
    writer.blank()


def _render_types(plan: StructsPlan) -> str:
    writer = FppWriter()
    _preamble(writer, plan, "every type the structs use", needs_types=False)
    with writer.module(plan.config.namespace):
        for definition in plan.type_defs:
            writer.blank()
            render_definition(
                writer,
                definition,
                lambda qualified: escape(type_name(qualified)),
                plan.spell,
            )
    return writer.render()


def _render_commands(plan: StructsPlan) -> str:
    writer = FppWriter()
    _preamble(writer, plan, "one struct and one opcode per command", needs_types=True)
    with writer.module(plan.config.namespace):
        writer.annotate("The remote's opcode for each command")
        with writer.module(OPCODE_MODULE):
            for struct in plan.commands:
                command = struct.source
                _constant(writer, struct.name, command.opcode, f"[{command.name}]")
        writer.blank()
        writer.annotate("Each command's arguments")
        with writer.module(COMMAND_MODULE):
            for index, struct in enumerate(plan.commands):
                command = struct.source
                note = f"[{command.name}] opcode {OPCODE_MODULE}.{struct.name}"
                if index:
                    writer.blank()
                _struct(
                    writer,
                    plan,
                    struct.name,
                    struct.fields,
                    f"{command.annotation}\n{note}" if command.annotation else note,
                )
    return writer.render()


def _render_packets(plan: StructsPlan) -> str:
    writer = FppWriter()
    _preamble(
        writer, plan, "one struct and one id per telemetry packet", needs_types=True
    )
    with writer.module(plan.config.namespace):
        writer.annotate("The remote's id for each telemetry packet")
        with writer.module(PACKET_ID_MODULE):
            for struct in plan.packets:
                _constant(
                    writer, struct.name, struct.source.id, f"[{struct.qualified_name}]"
                )
        writer.blank()
        writer.annotate(
            "Each packet's channels, in the order Svc.TlmPacketizer writes them.  A\n"
            "struct names the layout; it does not reproduce the packet's fixed-width\n"
            "slots, which pad a string channel out to its full capacity."
        )
        with writer.module(PACKET_MODULE):
            for index, struct in enumerate(plan.packets):
                if index:
                    writer.blank()
                _struct(
                    writer,
                    plan,
                    struct.name,
                    struct.fields,
                    f"[{struct.qualified_name}] id {PACKET_ID_MODULE}.{struct.name}, "
                    f"group {struct.source.group}",
                )
    return writer.render()


def _constant(writer: FppWriter, name: str, value: int, origin: str) -> None:
    """An FPP constant for an opcode or id, which the struct's default refers to."""
    writer.line(f"constant {escape(name)} = 0x{value:X} @< {origin}")


def _struct(
    writer: FppWriter,
    plan: StructsPlan,
    name: str,
    fields: Sequence[StructField],
    annotation: str,
) -> None:
    writer.annotate(annotation)
    defaults = ", ".join(
        f"{_field_name(field)} = {_qualified(field.default)}"
        for field in fields
        if field.default is not None
    )
    closing = f"}} default {{ {defaults} }}" if defaults else "}"
    if not fields:
        writer.line(f"struct {escape(name)} {{{closing}")
        return
    with writer.block(f"struct {escape(name)} {{", closing):
        for field in fields:
            text = f"{_field_name(field)}: {plan.spell(field.type)}"
            if field.annotation:
                text = f"{text} @< {' '.join(field.annotation.split())}"
            writer.line(text)


def _field_name(field: StructField) -> str:
    """A field's name as FPP spells it, and so as it reaches the generated C++."""
    return escape(safe_identifier(field.name))


def _qualified(name: str) -> str:
    """A dotted FPP name, each segment escaped."""
    return ".".join(escape(part) for part in name.split("."))
