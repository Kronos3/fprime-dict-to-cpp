"""Emitting the remote's type definitions, re-rooted into the proxy's component.

Defaults are deliberately omitted.  A default value in the dictionary is a literal
tree that may name enum constants by their *original* qualified path
(``"Ref.DpDemo.ColorEnum.RED"``), so carrying it over would mean rewriting those paths
in every nested position.  A default affects neither the wire format nor anything the
proxy does with a value, so the cost is not worth paying; FPP falls back to each type's
zero value.

The definitions are component members rather than module members, which is what gives
every generated name and file a ``<Component>_`` prefix and so keeps them from colliding
with a project that already has a type of that name.  It is also what lets the generated
C++ name the remote's ``FwOpcodeType`` as ``RefProxy_FwOpcodeType`` instead of aliasing
it: the wire widths are declared in the model, beside the members they apply to.
"""

from __future__ import annotations

from ..model import AliasDef, ArrayDef, EnumDef, StructDef, TypeDef
from ..plan import Plan
from ..spelling import safe_identifier
from .keywords import escape
from .writer import FppWriter, string_literal

__all__ = ["render_types"]


def render_types(plan: Plan) -> str:
    """Render the ``<Component>Types.fppi`` contents for ``plan``.

    An include fragment, not a file of its own: everything here is declared inside the
    component, so it has no module or component header to open.
    """
    writer = FppWriter()
    _preamble(writer, plan)

    writer.banner("Remote wire format")
    writer.comment(
        "The widths the remote deployment serialized its packet headers and string\n"
        "lengths with.  Declared whether or not a mirrored member uses one, because the\n"
        "decoders read every header field and string length at these widths --\n"
        "deliberately not at the local FwOpcodeType and friends, since a proxy has to\n"
        "agree with the sender."
    )
    for alias in plan.spelling.wire_type_defs():
        writer.blank()
        _alias(writer, plan, alias)

    writer.banner("Mirrored types")
    writer.comment(
        "Type definitions mirrored from the remote dictionary.  Names are the\n"
        "remote's qualified names flattened with '_', because fpp-to-cpp derives a\n"
        "generated file name from a type's leaf name and rejects duplicates.\n"
        "\n"
        "Aliases resolve to the width the REMOTE serialized, which is the point of\n"
        "re-declaring them: the local platform's FwSizeType may differ."
    )
    for definition in plan.spelling.type_defs():
        writer.blank()
        _definition(writer, plan, definition)
    return writer.render()


def _preamble(writer: FppWriter, plan: Plan) -> None:
    metadata = plan.dictionary.metadata
    writer.comment(
        f"Types used by {plan.config.component}, generated by fprime-dict-to-cpp.\n"
        f"\n"
        f"Included by {plan.config.component}.fpp, inside the component itself.\n"
        f"\n"
        f"Source deployment: {metadata.deployment_name}\n"
        f"Framework version: {metadata.framework_version}\n"
        f"Dictionary spec:   {metadata.spec_version}\n"
        f"\n"
        f"Do not edit: regenerate from the dictionary instead."
    )


def _definition(writer: FppWriter, plan: Plan, definition: TypeDef) -> None:
    """Render one type definition."""
    if isinstance(definition, EnumDef):
        _enum(writer, plan, definition)
    elif isinstance(definition, ArrayDef):
        _array(writer, plan, definition)
    elif isinstance(definition, StructDef):
        _struct(writer, plan, definition)
    elif isinstance(definition, AliasDef):
        _alias(writer, plan, definition)


def _name(plan: Plan, qualified: str) -> str:
    """The generated, escaped name for a type definition."""
    return escape(plan.spelling.namer.flat(qualified))


def _enum(writer: FppWriter, plan: Plan, definition: EnumDef) -> None:
    writer.annotate(_origin(definition.qualified_name, definition.annotation))
    representation = plan.spelling.fpp_type(definition.representation)
    with writer.block(
        f"enum {_name(plan, definition.qualified_name)}: {representation} {{"
    ):
        for constant in definition.constants:
            # An enum constant reaches the generated C++ bare, so it has to survive
            # both FPP's keyword table and C++'s.
            name = escape(safe_identifier(constant.name))
            suffix = (
                f"  @< {_one_line(constant.annotation)}" if constant.annotation else ""
            )
            writer.line(f"{name} = {constant.value}{suffix}")


def _array(writer: FppWriter, plan: Plan, definition: ArrayDef) -> None:
    writer.annotate(_origin(definition.qualified_name, definition.annotation))
    element = plan.spelling.fpp_type(definition.element)
    head = (
        f"array {_name(plan, definition.qualified_name)} = "
        f"[{definition.size}] {element}"
    )
    if definition.format:
        head = f"{head} format {string_literal(definition.format)}"
    writer.line(head)


def _struct(writer: FppWriter, plan: Plan, definition: StructDef) -> None:
    writer.annotate(_origin(definition.qualified_name, definition.annotation))
    with writer.block(f"struct {_name(plan, definition.qualified_name)} {{"):
        for member in definition.members:
            name = escape(safe_identifier(member.name))
            element = plan.spelling.fpp_type(member.type)
            # An inline array member: "arrayMemberU32: [2] U32".
            spelled = (
                f"[{member.array_size}] {element}" if member.array_size else element
            )
            text = f"{name}: {spelled}"
            if member.format:
                text = f"{text} format {string_literal(member.format)}"
            if member.annotation:
                text = f"{text} @< {_one_line(member.annotation)}"
            writer.line(text)


def _alias(writer: FppWriter, plan: Plan, definition: AliasDef) -> None:
    note = definition.annotation
    if definition.target.name != definition.underlying.name:
        # Record what was collapsed, since the generated alias no longer shows it.
        chased = f"resolved from {definition.target.name} to pin the remote's width"
        note = f"{note}\n{chased}" if note else chased
    writer.annotate(_origin(definition.qualified_name, note))
    underlying = plan.spelling.fpp_type(definition.underlying)
    writer.line(f"type {_name(plan, definition.qualified_name)} = {underlying}")


def _origin(qualified: str, annotation: str | None) -> str:
    """An annotation that keeps the remote's original name visible."""
    origin = f"[{qualified}]"
    return f"{annotation}\n{origin}" if annotation else origin


def _one_line(text: str) -> str:
    """Collapse an annotation to one line, for a trailing ``@<`` post-comment."""
    return " ".join(text.split())
